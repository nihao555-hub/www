// Distills VoltAgent/awesome-design-md (MIT) DESIGN.md files into a generated TS
// module the creative agent uses: a lightweight picker index + the (capped) full
// DESIGN.md text per brand, so the agent can pick a real brand design system and
// then "read" its design language when generating a site.
//
// Usage: node scripts/gen-brand-design-systems.mjs <path-to-awesome-design-md>
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const SRC = process.argv[2] || '/home/ubuntu/raw-templates/awesome-design-md'
const DESIGN_DIR = join(SRC, 'design-md')
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'ai', 'brand-design-md.generated.ts')
const MD_CAP = 8000

function prettyName(slug, frontName) {
  if (frontName) {
    const n = frontName.replace(/-?design-analysis$/i, '').replace(/-/g, ' ').trim()
    if (n) return n
  }
  return slug
    .replace(/\.(app|ai|com|io)$/i, '')
    .replace(/[-.]/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase())
}

function firstSentence(desc) {
  if (!desc) return ''
  const clean = desc.replace(/\s+/g, ' ').trim()
  const cut = clean.slice(0, 220)
  const dot = cut.lastIndexOf('. ')
  return (dot > 60 ? cut.slice(0, dot + 1) : cut).trim()
}

function parse(md) {
  const nameMatch = md.match(/^name:\s*(.+)$/m)
  // description may be quoted and span multiple lines until the next top-level key
  const descMatch = md.match(/^description:\s*([\s\S]*?)\n[a-zA-Z][a-zA-Z0-9_-]*:/m)
  let desc = descMatch ? descMatch[1] : ''
  desc = desc.replace(/^["']|["']$/g, '').replace(/^\s*>-?\s*/, '').trim()
  return { name: nameMatch ? nameMatch[1].trim() : '', description: desc }
}

const slugs = readdirSync(DESIGN_DIR).filter((d) => existsSync(join(DESIGN_DIR, d, 'DESIGN.md')))
const entries = []
for (const slug of slugs.sort()) {
  const raw = readFileSync(join(DESIGN_DIR, slug, 'DESIGN.md'), 'utf8')
  const { name, description } = parse(raw)
  const md = raw.length > MD_CAP ? raw.slice(0, MD_CAP) + '\n... (truncated)' : raw
  entries.push({
    id: slug,
    name: prettyName(slug, name),
    summary: firstSentence(description),
    md,
  })
}

const header = `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-brand-design-systems.mjs — DO NOT EDIT BY HAND.
// Source: VoltAgent/awesome-design-md (MIT, https://github.com/VoltAgent/awesome-design-md).
// ${entries.length} real brand design systems distilled for the creative agent.

export type BrandDesignSystem = {
  /** folder slug, e.g. "stripe", "linear.app" */
  id: string
  /** display name */
  name: string
  /** one-line aesthetic summary for the picker */
  summary: string
  /** the (capped) DESIGN.md the agent reads once it picks this brand */
  md: string
}

export const BRAND_DESIGN_SYSTEMS: BrandDesignSystem[] = `

writeFileSync(OUT, header + JSON.stringify(entries, null, 2) + '\n', 'utf8')
console.log(`Wrote ${entries.length} brand design systems to ${OUT} (${(JSON.stringify(entries).length / 1024).toFixed(0)} KB)`)
